"use client";

import Link from "next/link";
import { useMemo, useState } from "react";
import { Button } from "@/components/ui/button";

type GenerationDetail = {
  id: string;
  status: string;
  errorMessage: string | null;
  combinedStoredPdfId: string | null;
  generatedAt: string | Date;
  customerSnapshotJson: {
    displayName?: string;
    mobileNumber?: string | null;
    consumerNumber?: string | null;
  };
  documentSet: { id: string; name: string };
  documentSetVersion: { id: string; versionNumber: number };
  generatedBy: { id: string; name: string; email: string };
  documents: Array<{
    id: string;
    documentName: string;
    status: string;
    pageCount: number | null;
    template: { id: string; name: string };
    templateVersion: { id: string; versionNumber: number };
  }>;
};

function formatWhen(value: string | Date): string {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return String(value);
  return date.toLocaleString();
}

export function DocGenGenerationDetail({ generation }: { generation: GenerationDetail }) {
  const [previewDocId, setPreviewDocId] = useState<string | "combined">(
    generation.combinedStoredPdfId
      ? "combined"
      : (generation.documents.find((doc) => doc.status === "COMPLETED")?.id ?? "combined"),
  );

  const previewUrl = useMemo(() => {
    if (previewDocId === "combined") {
      if (!generation.combinedStoredPdfId) return null;
      return `/api/document-generator/generations/${generation.id}/pdf`;
    }
    return `/api/document-generator/generations/${generation.id}/pdf?documentId=${previewDocId}`;
  }, [generation.combinedStoredPdfId, generation.id, previewDocId]);

  const snapshot = generation.customerSnapshotJson ?? {};

  return (
    <div className="mx-auto max-w-4xl space-y-6 px-4 py-8">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold text-slate-900">Generation detail</h1>
          <p className="text-sm text-slate-600">
            {generation.documentSet.name} v{generation.documentSetVersion.versionNumber} ·{" "}
            {formatWhen(generation.generatedAt)}
          </p>
        </div>
        <div className="flex flex-wrap gap-2">
          <Button asChild variant="outline">
            <Link href="/documentation/document-generator/history">History</Link>
          </Button>
          <Button asChild variant="outline">
            <Link href="/documentation/document-generator/generate">Generate again</Link>
          </Button>
        </div>
      </div>

      <section className="space-y-2 rounded-lg border border-slate-200 bg-white p-4 text-sm">
        <p>
          <span className="text-slate-500">Status:</span> {generation.status}
        </p>
        <p>
          <span className="text-slate-500">Customer:</span> {snapshot.displayName ?? "—"}
          {snapshot.mobileNumber ? ` · ${snapshot.mobileNumber}` : ""}
          {snapshot.consumerNumber ? ` · ${snapshot.consumerNumber}` : ""}
        </p>
        <p>
          <span className="text-slate-500">Generated by:</span> {generation.generatedBy.name} (
          {generation.generatedBy.email})
        </p>
        <p>
          <span className="text-slate-500">Pinned set version:</span>{" "}
          {generation.documentSet.name} v{generation.documentSetVersion.versionNumber} (
          {generation.documentSetVersion.id})
        </p>
        {generation.errorMessage ? (
          <p className="text-amber-800">{generation.errorMessage}</p>
        ) : null}
      </section>

      <section className="space-y-3 rounded-lg border border-slate-200 bg-white p-4">
        <h2 className="font-semibold text-slate-900">Documents</h2>
        <ul className="space-y-2 text-sm">
          {generation.documents.map((doc) => (
            <li key={doc.id} className="flex flex-wrap items-center gap-2">
              <span>
                {doc.documentName} — {doc.status}
              </span>
              <span className="text-slate-500">
                {doc.template.name} v{doc.templateVersion.versionNumber}
                {doc.pageCount != null ? ` · ${doc.pageCount} page(s)` : ""}
              </span>
              {doc.status === "COMPLETED" ? (
                <a
                  className="text-emerald-700 hover:underline"
                  href={`/api/document-generator/generations/${generation.id}/pdf?documentId=${doc.id}`}
                  target="_blank"
                  rel="noreferrer"
                >
                  Download
                </a>
              ) : null}
            </li>
          ))}
        </ul>
        <div className="flex flex-wrap gap-2 pt-2">
          {generation.combinedStoredPdfId ? (
            <Button asChild>
              <a
                href={`/api/document-generator/generations/${generation.id}/pdf`}
                target="_blank"
                rel="noreferrer"
              >
                Download combined PDF
              </a>
            </Button>
          ) : null}
        </div>
      </section>

      <section className="space-y-3 rounded-lg border border-slate-200 bg-white p-4">
        <h2 className="font-semibold text-slate-900">Preview</h2>
        <div className="flex flex-wrap gap-2">
          {generation.combinedStoredPdfId ? (
            <Button
              type="button"
              size="sm"
              variant={previewDocId === "combined" ? "default" : "outline"}
              onClick={() => setPreviewDocId("combined")}
            >
              Combined
            </Button>
          ) : null}
          {generation.documents
            .filter((doc) => doc.status === "COMPLETED")
            .map((doc) => (
              <Button
                key={doc.id}
                type="button"
                size="sm"
                variant={previewDocId === doc.id ? "default" : "outline"}
                onClick={() => setPreviewDocId(doc.id)}
              >
                {doc.documentName}
              </Button>
            ))}
        </div>
        {previewUrl ? (
          <iframe
            title="Generation preview"
            src={previewUrl}
            className="h-[70vh] w-full rounded border border-slate-200 bg-slate-50"
          />
        ) : (
          <p className="text-sm text-slate-600">No PDF available to preview.</p>
        )}
      </section>
    </div>
  );
}
